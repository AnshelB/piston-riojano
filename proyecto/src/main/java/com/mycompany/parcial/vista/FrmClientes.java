    private void limpiarFormulario() {
        jtfDni.setText("");
        jtfNombre.setText("");
        jtfApellido.setText("");
        jtfTelefono.setText("");
        jtfEmail.setText("");
        jtfDni.setEditable(true);
        jtClientes.clearSelection();
    }

    private void cargarTabla() {
        modeloTabla.setRowCount(0);
        try {
            for (Cliente c : clienteDAO.listar()) {
                modeloTabla.addRow(new Object[]{
                    c.getDni(), c.getNombre(), c.getApellido(), c.getTelefono(), c.getEmail()});
            }
        } catch (SQLException e) {
            mostrarErrorBD(e);
        }
    }

    private void cargarCamposDesdeFila() {
        int fila = jtClientes.getSelectedRow();
        if (fila < 0) {
            return;
        }
        jtfDni.setText(textoDe(modeloTabla.getValueAt(fila, 0)));
        jtfNombre.setText(textoDe(modeloTabla.getValueAt(fila, 1)));
        jtfApellido.setText(textoDe(modeloTabla.getValueAt(fila, 2)));
        jtfTelefono.setText(textoDe(modeloTabla.getValueAt(fila, 3)));
        jtfEmail.setText(textoDe(modeloTabla.getValueAt(fila, 4)));
        jtfDni.setEditable(false);
    }

    private String textoDe(Object valor) {
        return valor == null ? "" : valor.toString();
    }

    private Cliente leerCliente() {
        String dni = jtfDni.getText().trim();
        String nombre = jtfNombre.getText().trim();
        String apellido = jtfApellido.getText().trim();
        String telefono = jtfTelefono.getText().trim();
        String email = jtfEmail.getText().trim();

        if (dni.isEmpty() || nombre.isEmpty() || apellido.isEmpty() || telefono.isEmpty()) {
            mostrarAviso("Completa los campos obligatorios (marcados con *).");
            return null;
        }
        if (!dni.matches("\\d{7,8}")) {
            mostrarAviso("El DNI debe tener 7 u 8 digitos, solo numeros.");
            return null;
        }
        if (!telefono.matches("\\d{6,15}")) {
            mostrarAviso("El telefono debe tener entre 6 y 15 digitos, solo numeros.");
            return null;
        }
        if (!email.isEmpty() && !email.matches("[^@\\s]+@[^@\\s]+\\.[^@\\s]+")) {
            mostrarAviso("El email no tiene un formato valido.");
            return null;
        }
        return new Cliente(dni, nombre, apellido, telefono, email.isEmpty() ? null : email);
    }

    private void mostrarAviso(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Atencion", JOptionPane.WARNING_MESSAGE);
    }

    private void mostrarErrorBD(SQLException e) {
        JOptionPane.showMessageDialog(this,
                "No se pudo completar la operacion en la base de datos:\n" + e.getMessage(),
                "Error de Base de Datos", JOptionPane.ERROR_MESSAGE);
    }

