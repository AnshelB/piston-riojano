    private void jbAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbAgregarActionPerformed
        Cliente c = leerCliente();
        if (c == null) {
            return;
        }
        try {
            if (clienteDAO.buscarPorDni(c.getDni()) != null) {
                mostrarAviso("Ya existe un cliente con el DNI " + c.getDni() + ".");
                return;
            }
            clienteDAO.insertar(c);
            limpiarFormulario();
            cargarTabla();
            JOptionPane.showMessageDialog(this, "Cliente agregado correctamente.",
                    "Operacion exitosa", JOptionPane.INFORMATION_MESSAGE);
        } catch (SQLException e) {
            mostrarErrorBD(e);
        }
    }//GEN-LAST:event_jbAgregarActionPerformed

    private void jbModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbModificarActionPerformed
        if (jtfDni.isEditable()) {
            mostrarAviso("Selecciona un cliente de la tabla para modificarlo.");
            return;
        }
        Cliente c = leerCliente();
        if (c == null) {
            return;
        }
        try {
            clienteDAO.modificar(c);
            limpiarFormulario();
            cargarTabla();
            JOptionPane.showMessageDialog(this, "Cliente modificado correctamente.",
                    "Operacion exitosa", JOptionPane.INFORMATION_MESSAGE);
        } catch (SQLException e) {
            mostrarErrorBD(e);
        }
    }//GEN-LAST:event_jbModificarActionPerformed

    private void jbEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbEliminarActionPerformed
        int fila = jtClientes.getSelectedRow();
        if (fila < 0) {
            mostrarAviso("Selecciona un cliente de la tabla para eliminarlo.");
            return;
        }
        String dni = (String) modeloTabla.getValueAt(fila, 0);
        try {
            if (clienteDAO.tieneVehiculos(dni)) {
                mostrarAviso("No se puede eliminar el cliente porque tiene vehiculos registrados.");
                return;
            }
            int opcion = JOptionPane.showConfirmDialog(this,
                    "Seguro que deseas eliminar al cliente con DNI " + dni + "?",
                    "Confirmar baja", JOptionPane.YES_NO_OPTION);
            if (opcion != JOptionPane.YES_OPTION) {
                return;
            }
            clienteDAO.eliminar(dni);
            limpiarFormulario();
            cargarTabla();
            JOptionPane.showMessageDialog(this, "Cliente eliminado correctamente.",
                    "Operacion exitosa", JOptionPane.INFORMATION_MESSAGE);
        } catch (SQLException e) {
            mostrarErrorBD(e);
        }
    }//GEN-LAST:event_jbEliminarActionPerformed

