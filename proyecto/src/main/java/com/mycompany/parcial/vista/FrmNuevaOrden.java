    private void limpiarFormulario() {
        orden = null;
        jtfDescripcion.setText("");
        jtfHoras.setText("");
        jtfCantidad.setText("");
        bloquearCabecera(false);
        cargarCombos();
        refrescarDetalle();
    }

    private void bloquearCabecera(boolean bloquear) {
        jcbVehiculo.setEnabled(!bloquear);
        jcbMecanico.setEnabled(!bloquear);
        jtfDescripcion.setEditable(!bloquear);
        jtfHoras.setEditable(!bloquear);
    }

    private void cargarCombos() {
        jcbVehiculo.removeAllItems();
        jcbMecanico.removeAllItems();
        jcbRepuesto.removeAllItems();
        try {
            for (Vehiculo v : vehiculoDAO.listarTodos()) {
                jcbVehiculo.addItem(v);
            }
            for (Mecanico m : mecanicoDAO.listar()) {
                jcbMecanico.addItem(m);
            }
            for (Repuesto r : repuestoDAO.listar()) {
                jcbRepuesto.addItem(r);
            }
        } catch (SQLException e) {
            mostrarErrorBD(e);
        }
        mostrarStockDelRepuesto();
    }

    // recarga combos solo si no hay una carga a medias
    public void recargarCombos() {
        if (orden == null) {
            cargarCombos();
        }
    }

    private void mostrarStockDelRepuesto() {
        Repuesto r = (Repuesto) jcbRepuesto.getSelectedItem();
        jlblStock.setText(r == null ? "Stock: 0" : "Stock: " + r.getStockDisponible());
    }

    private void refrescarDetalle() {
        modeloDetalle.setRowCount(0);
        double sumaRepuestos = 0;
        double manoDeObra = 0;
        if (orden != null) {
            for (DetalleOrden d : orden.getDetalles()) {
                modeloDetalle.addRow(new Object[] {
                        d.getRepuesto().getCodigo(),
                        d.getRepuesto().getDescripcion(),
                        d.getCantidad(),
                        dinero(d.getPrecioAplicado()),
                        dinero(d.calcularSubtotal()) });
                sumaRepuestos += d.calcularSubtotal();
            }
            manoDeObra = orden.calcularManoDeObra();
        }
        jlblManoObra.setText("Mano de obra: " + dinero(manoDeObra));
        jlblRepuestos.setText("Repuestos: " + dinero(sumaRepuestos));
        jlblTotal.setText("TOTAL: " + dinero(orden == null ? 0 : orden.calcularTotal()));
    }

    private String dinero(double valor) {
        return String.format("$ %,.2f", valor);
    }

    private Integer parsearEntero(String texto) {
        try {
            return Integer.valueOf(texto.trim());
        } catch (NumberFormatException e) {
            return null;
        }
    }

    private Double parsearHoras(String texto) {
        try {
            double valor = Double.parseDouble(texto.trim().replace(',', '.'));
            if (Double.isNaN(valor) || Double.isInfinite(valor) || valor < 0 || valor > 9999) {
                return null;
            }
            return Math.round(valor * 100) / 100.0;
        } catch (NumberFormatException e) {
            return null;
        }
    }

    private void mostrarAviso(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Atencion", JOptionPane.WARNING_MESSAGE);
    }

    private void mostrarErrorBD(SQLException e) {
        JOptionPane.showMessageDialog(this,
                "No se pudo completar la operacion en la base de datos:\n" + e.getMessage(),
                "Error de Base de Datos", JOptionPane.ERROR_MESSAGE);
    }

