    private void actualizar() {
        int fila = jtRepuestos.getSelectedRow();
        if (fila < 0) {
            mostrarAviso("Selecciona un repuesto de la tabla para actualizarlo.");
            return;
        }
        Double precio = parsearPrecio(jtfPrecio.getText());
        if (precio == null) {
            mostrarAviso("El precio debe ser un numero mayor o igual a cero (ej. 15000 o 15000.50).");
            return;
        }
        Integer stock = parsearEntero(jtfStock.getText());
        if (stock == null || stock < 0) {
            mostrarAviso("El stock debe ser un numero entero mayor o igual a cero.");
            return;
        }

        Repuesto repuesto = repuestos.get(fila);
        repuesto.setPrecioUnitarioActual(precio);
        repuesto.setStockDisponible(stock);
        try {
            repuestoDAO.actualizar(repuesto);
            JOptionPane.showMessageDialog(this, "Repuesto actualizado correctamente.",
                    "Operacion exitosa", JOptionPane.INFORMATION_MESSAGE);
        } catch (SQLException e) {
            mostrarErrorBD(e);
        }
        limpiarFormulario();
        cargarTabla();
    }

    private void limpiarFormulario() {
        jtfCodigo.setText("");
        jtfDescripcion.setText("");
        jtfPrecio.setText("");
        jtfStock.setText("");
        jtRepuestos.clearSelection();
    }

    private void cargarTabla() {
        modeloTabla.setRowCount(0);
        repuestos = new ArrayList<>();
        try {
            repuestos = repuestoDAO.listar();
            for (Repuesto r : repuestos) {
                modeloTabla.addRow(new Object[]{
                    r.getCodigo(),
                    r.getDescripcion(),
                    String.format("$ %,.2f", r.getPrecioUnitarioActual()),
                    r.getStockDisponible()});
            }
        } catch (SQLException e) {
            mostrarErrorBD(e);
        }
    }

    private void cargarCamposDesdeFila() {
        int fila = jtRepuestos.getSelectedRow();
        if (fila < 0 || fila >= repuestos.size()) {
            return;
        }
        Repuesto r = repuestos.get(fila);
        jtfCodigo.setText(r.getCodigo());
        jtfDescripcion.setText(r.getDescripcion());
        jtfPrecio.setText(String.format(Locale.US, "%.2f", r.getPrecioUnitarioActual()));
        jtfStock.setText(String.valueOf(r.getStockDisponible()));
    }

    private Double parsearPrecio(String texto) {
        try {
            double valor = Double.parseDouble(texto.trim().replace(',', '.'));
            if (Double.isNaN(valor) || Double.isInfinite(valor) || valor < 0) {
                return null;
            }
            return Math.round(valor * 100) / 100.0;
        } catch (NumberFormatException e) {
            return null;
        }
    }

    private Integer parsearEntero(String texto) {
        try {
            return Integer.valueOf(texto.trim());
        } catch (NumberFormatException e) {
            return null;
        }
    }

    private void mostrarAviso(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Atencion", JOptionPane.WARNING_MESSAGE);
    }

