    private void jbAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbAgregarActionPerformed
        Cliente cliente = (Cliente) jcbCliente.getSelectedItem();
        if (cliente == null) {
            mostrarAviso("Tenes que seleccionar un cliente.");
            return;
        }

        String patente = jtfPatente.getText().trim().toUpperCase();
        String marca = jtfMarca.getText().trim();
        String modelo = jtfModelo.getText().trim();
        Integer anio = parsearEntero(jtfAnio.getText());

        if (patente.isEmpty() || marca.isEmpty() || modelo.isEmpty() || anio == null) {
            mostrarAviso("Completa los datos basicos del vehiculo (patente, marca, modelo y año).");
            return;
        }

        int anioActual = Year.now().getValue();
        if (anio < 1900 || anio > anioActual + 1) {
            mostrarAviso("El año debe estar entre 1900 y " + (anioActual + 1) + ".");
            return;
        }

        Vehiculo vehiculo;
        if (jrbAuto.isSelected()) {
            Integer puertas = parsearEntero(jtfPuertas.getText());
            if (puertas == null || puertas < 2 || puertas > 6) {
                mostrarAviso("La cantidad de puertas debe ser un numero entre 2 y 6.");
                return;
            }
            TipoCombustible combustible = (TipoCombustible) jcbCombustible.getSelectedItem();
            if (combustible == null) {
                mostrarAviso("Selecciona un tipo de combustible.");
                return;
            }
            vehiculo = new Auto(patente, marca, modelo, anio, cliente, puertas, combustible);
        } else {
            Integer cilindrada = parsearEntero(jtfCilindrada.getText());
            if (cilindrada == null || cilindrada <= 0) {
                mostrarAviso("La cilindrada debe ser un numero mayor a cero.");
                return;
            }
            vehiculo = new Moto(patente, marca, modelo, anio, cliente, cilindrada);
        }

        try {
            if (vehiculoDAO.buscarPorPatente(patente) != null) {
                mostrarAviso("Ya existe un vehiculo con esa patente.");
                return;
            }
            vehiculoDAO.insertar(vehiculo);
            limpiarFormulario();
            cargarTabla();
            JOptionPane.showMessageDialog(this, "Vehiculo agregado correctamente.",
                    "Operacion exitosa", JOptionPane.INFORMATION_MESSAGE);
        } catch (SQLException e) {
            mostrarErrorBD(e);
        }
    }//GEN-LAST:event_jbAgregarActionPerformed

