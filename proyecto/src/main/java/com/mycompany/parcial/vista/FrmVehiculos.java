    private void habilitarCamposPorTipo() {
        boolean esAuto = jrbAuto.isSelected();
        jtfPuertas.setEnabled(esAuto);
        jcbCombustible.setEnabled(esAuto);
        jtfCilindrada.setEnabled(!esAuto);
    }

    private void limpiarFormulario() {
        jtfPatente.setText("");
        jtfMarca.setText("");
        jtfModelo.setText("");
        jtfAnio.setText("");
        jtfPuertas.setText("");
        jtfCilindrada.setText("");
        jcbCombustible.setSelectedIndex(0);
        jrbAuto.setSelected(true);
        habilitarCamposPorTipo();
    }

    private void cargarClientes() {
        jcbCliente.removeAllItems();
        try {
            for (Cliente c : clienteDAO.listar()) {
                jcbCliente.addItem(c);
            }
        } catch (SQLException e) {
            mostrarErrorBD(e);
        }
    }
     // Se llama cuando la ventana ya estaba abierta y se vuelve a ella:
    // vuelve a leer los clientes (por si hay uno nuevo) y mantiene el que estaba elegido
    public void recargarClientes() {
        Cliente elegido = (Cliente) jcbCliente.getSelectedItem();
        cargarClientes();
        if (elegido != null) {
            for (int i = 0; i < jcbCliente.getItemCount(); i++) {
                if (jcbCliente.getItemAt(i).getDni().equals(elegido.getDni())) {
                    jcbCliente.setSelectedIndex(i);
                    break;
                }
            }
        }
    }

    private void cargarTabla() {
        modeloTabla.setRowCount(0);
        Cliente cliente = (Cliente) jcbCliente.getSelectedItem();
        if (cliente == null) {
            return;
        }
        try {
            for (Vehiculo v : vehiculoDAO.listarPorCliente(cliente.getDni())) {
                modeloTabla.addRow(new Object[]{
                    v.getPatente(), v.getMarca(), v.getModelo(), v.getAnio(),
                    tipoDe(v), detalleDe(v), v.calcularCoeficiente()});
            }
        } catch (SQLException e) {
            mostrarErrorBD(e);
        }
    }

    private String tipoDe(Vehiculo v) {
        return v instanceof Auto ? "Auto" : "Moto";
    }

    private String detalleDe(Vehiculo v) {
        if (v instanceof Auto auto) {
            return auto.getCantidadPuertas() + " puertas, " + auto.getTipoCombustible();
        }
        if (v instanceof Moto moto) {
            return moto.getCilindrada() + " cc";
        }
        return "";
    }

    private Integer parsearEntero(String texto) {
        try {
            return Integer.valueOf(texto.trim());
        } catch (NumberFormatException e) {
            return null;
        }
    }

    private void mostrarAviso(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Atencion", JOptionPane.WARNING_MESSAGE);
    }

    private void mostrarErrorBD(SQLException e) {
        JOptionPane.showMessageDialog(this,
                "No se pudo completar la operacion en la base de datos:\n" + e.getMessage(),
                "Error de Base de Datos", JOptionPane.ERROR_MESSAGE);
    }

