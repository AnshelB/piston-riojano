    private void cambiarEstado() {
        int fila = jtOrdenes.getSelectedRow();
        if (fila < 0) {
            mostrarAviso("Selecciona una orden de la tabla para cambiar su estado.");
            return;
        }
        OrdenTrabajo orden = ordenes.get(fila);
        EstadoOrden nuevoEstado = (EstadoOrden) jcbNuevoEstado.getSelectedItem();

        try {
            orden.cambiarEstado(nuevoEstado);
        } catch (IllegalStateException e) {
            mostrarAviso(e.getMessage());
            return;
        }

        try {
            ordenDAO.actualizarEstado(orden);
            JOptionPane.showMessageDialog(this, "La orden N° " + orden.getNumero()
                    + " ahora esta en estado " + nuevoEstado + ".",
                    "Operacion exitosa", JOptionPane.INFORMATION_MESSAGE);
        } catch (SQLException e) {
            mostrarErrorBD(e);
        }
        cargarTabla();
    }

    private EstadoOrden estadoFiltro() {
        int indice = jcbFiltro.getSelectedIndex();
        return indice <= 0 ? null : EstadoOrden.values()[indice - 1];
    }

    private void cargarTabla() {
        modeloTabla.setRowCount(0);
        ordenes = new ArrayList<>();
        try {
            ordenes = ordenDAO.listar(estadoFiltro());
            for (OrdenTrabajo o : ordenes) {
                modeloTabla.addRow(new Object[] {
                        o.getNumero(),
                        o.getFechaIngreso().format(FORMATO_FECHA),
                        o.getVehiculo().getPatente(),
                        o.getMecanico().getApellido() + ", " + o.getMecanico().getNombre(),
                        o.getEstado(),
                        String.format("$ %,.2f", o.calcularTotal()) });
            }
        } catch (SQLException e) {
            mostrarErrorBD(e);
        }
        jlblSeleccion.setText("Selecciona una orden para ver su descripcion.");
    }

    private void alSeleccionarOrden() {
        int fila = jtOrdenes.getSelectedRow();
        if (fila < 0 || fila >= ordenes.size()) {
            return;
        }
        OrdenTrabajo orden = ordenes.get(fila);
        jlblSeleccion.setText("Orden N° " + orden.getNumero() + ": " + orden.getDescripcionProblema());

        EstadoOrden[] estados = EstadoOrden.values();
        int siguiente = orden.getEstado().ordinal() + 1;
        if (siguiente < estados.length) {
            jcbNuevoEstado.setSelectedItem(estados[siguiente]);
        }
    }

    private void mostrarAviso(String mensaje) {
        JOptionPane.showMessageDialog(this, mensaje, "Atencion", JOptionPane.WARNING_MESSAGE);
    }

    private void mostrarErrorBD(SQLException e) {
        JOptionPane.showMessageDialog(this,
                "No se pudo completar la operacion en la base de datos:\n" + e.getMessage(),
                "Error de Base de Datos", JOptionPane.ERROR_MESSAGE);
    }

